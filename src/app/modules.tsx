const statusAction = (
  key: string,
  label: string,
  roles: Role[],
  endpoint: (record: GenericRecord) => string,
  options: { label: string; value: string }[],
): ActionConfig<GenericRecord> => ({
  key,
  label,
  roles,
  method: 'patch',
  endpoint,
  fields: [
    {
      name: 'Estado',
      label: 'Nuevo estado',
      type: 'select',
      required: true,
      options,
    },
  ],
  buildPayload: (values, _record, username) => ({
    Estado: values.Estado,
    Usuario: username,
  }),
  successMessage: `${label} ejecutado correctamente.`,
  variant: 'accent',
});

const withCreateAudit = (values: Record<string, unknown>, username: string, fieldName = 'CreadoPorUsuario') => ({
  ...sanitizePayload(values, 'create'),
  [fieldName]: username,
});

const withUpdateAudit = (values: Record<string, unknown>, username: string, fieldName = 'ModificadoPorUsuario') => ({
  ...sanitizePayload(values, 'update'),
  [fieldName]: username,
});

function sanitizePayload(values: Record<string, unknown>, mode: 'create' | 'update') {
  const payload = { ...values };
  const keysToDrop = [
    'EsEliminado',
    'FechaRegistroUtc',
    'FechaModificacionUtc',
    'FechaInhabilitacionUtc',
    'MotivoInhabilitacion',
    'ModificacionIp',
    'ServicioOrigen',
    'RowVersion',
  ];

  for (const key of keysToDrop) {
    delete payload[key];
  }

  if (mode === 'create') {
    for (const key of Object.keys(payload)) {
      if (key.endsWith('Guid') || key.startsWith('Guid')) {
        delete payload[key];
      }
    }
  }

  return payload;
}

